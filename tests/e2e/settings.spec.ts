import { test, expect } from '@playwright/test'

test('configuration forms reject blank names, invalid amounts and rates without losing input', async ({ page }) => {
  await page.goto('/#/cards/new')
  await page.getByLabel('卡片名稱').fill('   ')
  await page.getByRole('button', { name: '儲存卡片' }).click()
  await expect(page.getByRole('alert')).toContainText('名稱')
  await expect(page.getByLabel('卡片名稱')).toHaveValue('   ')
  await page.getByLabel('卡片名稱').fill('測試卡')
  await page.getByRole('button', { name: '儲存卡片' }).click()
  await page.getByRole('link', { name: '新增加碼活動', exact: true }).click()
  await page.getByLabel('活動名稱').fill('日本指定商店')
  await page.getByLabel('回饋上限（台幣）').fill('500')
  await page.getByLabel('加碼百分比（%）').fill('0')
  await page.getByRole('button', { name: '儲存活動' }).click()
  await expect(page.getByRole('alert')).toContainText('加碼百分比')
  await expect(page.getByLabel('回饋上限（台幣）')).toHaveValue('500')
  await page.getByLabel('加碼百分比（%）').fill('6')
  await page.getByLabel('回饋上限（台幣）').fill('-1')
  await page.getByRole('button', { name: '儲存活動' }).click()
  await expect(page.getByRole('alert')).toContainText('金額')
  await page.getByLabel('回饋上限（台幣）').fill('500')
  await page.getByRole('button', { name: '儲存活動' }).click()
  await expect(page.locator('.amount')).toContainText('8,333')
  await page.getByRole('link', { name: '新增活動', exact: true }).click()
  await page.getByLabel('活動名稱').fill('網購加碼')
  await page.getByLabel('回饋上限（台幣）').fill('300')
  await page.getByLabel('加碼百分比（%）').fill('3')
  await page.getByRole('button', { name: '儲存活動' }).click()
  await expect(page.getByRole('heading', { name: '測試卡', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.activity-panel').filter({ has: page.getByRole('heading', { name: '日本指定商店', exact: true }) }).locator('.amount')).toContainText('8,333')
  await expect(page.locator('.activity-panel').filter({ has: page.getByRole('heading', { name: '網購加碼', exact: true }) }).locator('.amount')).toContainText('10,000')
})
